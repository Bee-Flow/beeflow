#!/usr/bin/env node
/**
 * Migration: Knowledge Base usage contexts + source kind.
 *
 *   - `usage_contexts JSONB` — array of strings; one or more of
 *       'agent', 'direct_chat', 'webpage'. Drives which KB pickers
 *       this KB shows up in. Default = all three.
 *   - `source_kind TEXT` — 'manual' | 'webpage_auto' | 'notebook_auto'.
 *       Auto-created KBs (owned by the webpage/notebook UI) are hidden
 *       from the main marketplace. Default = 'manual'.
 *
 * Idempotent — uses ADD COLUMN IF NOT EXISTS and a guarded UPDATE so
 * rows already classified as `webpage_auto`/`notebook_auto` are never
 * re-touched. Safe to run on every server start.
 *
 * Auto-runs from `stores/knowledgeBases.js initDB()`. Manual usage:
 *   node server/migrations/add-kb-usage-contexts.js
 */

const { exec } = require('../db');

async function up() {
    await exec(`
        ALTER TABLE knowledge_bases
            ADD COLUMN IF NOT EXISTS usage_contexts JSONB
            DEFAULT '["agent","direct_chat","webpage"]'::jsonb
    `);
    await exec(`
        ALTER TABLE knowledge_bases
            ADD COLUMN IF NOT EXISTS source_kind TEXT
            DEFAULT 'manual'
    `);

    // Backfill: classify rows that were auto-generated by the webpage/notebook
    // flows. We only touch rows still flagged 'manual' so re-runs are a no-op.
    await exec(`
        UPDATE knowledge_bases
           SET source_kind = 'webpage_auto',
               usage_contexts = '["webpage"]'::jsonb
         WHERE source_kind = 'manual'
           AND name LIKE '🌐 %'
           AND description LIKE 'Auto-generated knowledge base for webpage%'
    `);
    await exec(`
        UPDATE knowledge_bases
           SET source_kind = 'notebook_auto',
               usage_contexts = '["webpage"]'::jsonb
         WHERE source_kind = 'manual'
           AND name LIKE '📓 %'
           AND description LIKE 'Auto-generated knowledge base for notebook%'
    `);

    // Index source_kind so the marketplace filter (source_kind='manual') is cheap.
    try { await exec(`CREATE INDEX IF NOT EXISTS idx_kb_source_kind ON knowledge_bases(source_kind)`); } catch (_) {}

    // The 'webpage' usage-context is no longer offered to users from the studio
    // (auto-created webpage KBs already live with `source_kind='webpage_auto'`).
    // Strip 'webpage' from any manual KB still carrying the original default
    // value `["agent","direct_chat","webpage"]` so existing manual KBs continue
    // to show up in the studio. Targeted to the unchanged-default value so
    // manual KBs that were explicitly configured for webpages are left alone.
    await exec(`
        UPDATE knowledge_bases
           SET usage_contexts = '["agent","direct_chat"]'::jsonb
         WHERE source_kind = 'manual'
           AND usage_contexts = '["agent","direct_chat","webpage"]'::jsonb
    `);

    console.log('[Migration] add-kb-usage-contexts applied');
}

module.exports = { up };

if (require.main === module) {
    up().then(() => process.exit(0)).catch(err => {
        console.error(err);
        process.exit(1);
    });
}
