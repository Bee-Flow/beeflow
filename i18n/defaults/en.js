// Get all namespace categories for the GUI editor filter
function getGUINamespaces() {
    const namespaces = new Set();
    for (const key of Object.keys(GUI_DEFAULTS)) {
        const ns = key.split('.')[0];
        namespaces.add(ns);
    }
    return Array.from(namespaces).sort();
}

